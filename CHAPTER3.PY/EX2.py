# Tạo danh sách chứa 3 người bạn
ban_be = ["An", "Bình", "Chi"]

# In danh sách ban đầu
print("Danh sách ban đầu:", ban_be)

# Thêm một người bạn mới vào cuối danh sách
ban_be.append("Dũng")
print("Sau khi thêm bạn mới:", ban_be)

# Xóa người bạn ở vị trí thứ hai (chỉ số 1)
ban_be.pop(1)
print("Sau khi xóa bạn ở vị trí thứ hai:", ban_be)